import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const outputPath = fileURLToPath(
  new URL('../packages/api-client/src/generated/openapi.d.ts', import.meta.url),
)
const openapiUrl = process.env.OPENAPI_URL ?? 'http://127.0.0.1:8090/openapi.json'
const configuredOpenapiFile = process.env.OPENAPI_FILE
const bundledOpenapiFile = fileURLToPath(new URL('../openapi.json', import.meta.url))
const openapiFile = configuredOpenapiFile ?? bundledOpenapiFile
const check = process.argv.includes('--check')

let document
try {
  document = JSON.parse(await readFile(openapiFile, 'utf8'))
} catch (error) {
  if (configuredOpenapiFile || error?.code !== 'ENOENT') throw error
  const response = await fetch(openapiUrl)
  if (!response.ok) {
    throw new Error(`OpenAPI export failed: ${response.status} ${openapiUrl}`)
  }
  document = await response.json()
}

const ast = await openapiTS(document)
const generated = `// Generated by scripts/generate-openapi-types.mjs from ${configuredOpenapiFile ?? openapiUrl}\n${astToString(ast)}`

if (check) {
  const current = await readFile(outputPath, 'utf8')
  if (current !== generated) {
    throw new Error('OpenAPI types are stale. Run pnpm openapi:generate.')
  }
} else {
  await writeFile(outputPath, generated, 'utf8')
}
